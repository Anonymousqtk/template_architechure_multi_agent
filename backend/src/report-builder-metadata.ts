const ROLE_RANKS: Record<RoleName, number> = {
  ADMIN: 4,
  HR: 3,
  MANAGER: 2,
  EMPLOYEE: 1,
};

export function hasMinRole(userRole: string, minRole: RoleName): boolean {
  return (ROLE_RANKS[userRole as RoleName] ?? 0) >= ROLE_RANKS[minRole];
}

