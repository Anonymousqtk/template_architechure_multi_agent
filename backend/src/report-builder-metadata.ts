export function getAuthorizedMetadata(role: string, locale: 'vi' | 'en') {
  const authorizedEntities = Object.values(REPORT_ENTITIES)
    .filter((entity) => hasMinRole(role, entity.minRole))
    .map((entity) => ({
      id: entity.id,
      label: locale === 'en' ? entity.labelEn : entity.labelVi,
      description: locale === 'en' ? entity.descriptionEn : entity.descriptionVi,
      grain: entity.grain,
      minRole: entity.minRole,
      allowedRelations: entity.allowedRelations
        .filter((rel) => hasMinRole(role, REPORT_ENTITIES[rel.targetEntity].minRole))
        .map((rel) => ({
          targetEntity: rel.targetEntity,
          cardinality: rel.cardinality,
          label: locale === 'en' ? rel.labelEn : rel.labelVi,
          description: locale === 'en' ? rel.descriptionEn : rel.descriptionVi,
        })),
    }));

  const authorizedEntityIds = new Set(authorizedEntities.map((e) => e.id));

  const authorizedFields = REPORT_FIELDS.filter(
    (field) => authorizedEntityIds.has(field.entity) && hasMinRole(role, field.minRole),
  ).map((field) => ({
    id: field.id,
    entity: field.entity,
    category: locale === 'en' ? field.categoryEn : field.categoryVi,
    label: locale === 'en' ? field.labelEn : field.labelVi,
    description: locale === 'en' ? field.descriptionEn : field.descriptionVi,
    dataType: field.dataType,
    allowedAggregations: field.allowedAggregations,
    filterOperators: field.filterOperators,
    formatOptions: field.formatOptions,
    defaultFormat: field.defaultFormat,
    minRole: field.minRole,
    groupable: field.groupable,
    pivotable: field.pivotable,
    sortable: field.sortable,
    isAdditive: field.isAdditive ?? false,
    enumValues: field.enumValues?.map((opt) => ({
      value: opt.value,
      label: locale === 'en' ? opt.labelEn : opt.labelVi,
    })),
  }));

  return {
    entities: authorizedEntities,
    fields: authorizedFields,
    templates: PREBUILT_REPORT_TEMPLATES.filter((tpl) => hasMinRole(role, tpl.minRole)).map(
      (tpl) => ({
        templateCode: tpl.templateCode,
        name: locale === 'en' ? tpl.nameEn : tpl.nameVi,
        description: locale === 'en' ? tpl.descriptionEn : tpl.descriptionVi,
        primaryEntity: tpl.primaryEntity,
        relatedEntities: tpl.relatedEntities,
        visualizationType: tpl.visualizationType,
        definition: tpl.definition,
      }),
    ),
  };
}
